import Foundation

enum TranslationEngine: String, CaseIterable {
    case apple, google
}

enum TranslationLanguageDefaults {
    static let source = "en"
    static let target = "zh-Hant"
    static let languages = ["zh-Hant", "en", "ja"]
}

/// Presentation is independent of the request: expanding must not restart a
/// translation or discard the copied original.
enum TranslationPresentation: Equatable {
    case compact, editor

    var preferredSize: CGSize {
        switch self {
        case .compact: return CGSize(width: TranslationCompactLayout.defaultWidth, height: 230)
        case .editor: return CGSize(width: 880, height: 520)
        }
    }

    var minimumSize: CGSize {
        switch self {
        case .compact: return CGSize(width: 400, height: 210)
        case .editor: return CGSize(width: 620, height: 380)
        }
    }
}

enum TranslationCompactLayout {
    static let defaultWidth = 630.0
    static let defaultFontSize = 20.0
    static let widthRange = 400.0...1_200.0
    static let fontSizeRange = 12.0...32.0

    static func width(_ value: Double) -> Double {
        guard value.isFinite, value > 0 else { return defaultWidth }
        return min(max(value, widthRange.lowerBound), widthRange.upperBound)
    }

    static func fontSize(_ value: Double) -> Double {
        guard value.isFinite, value > 0 else { return defaultFontSize }
        return min(max(value, fontSizeRange.lowerBound), fontSizeRange.upperBound)
    }

    static func height(for measuredHeight: CGFloat, available: CGFloat) -> CGFloat {
        min(max(TranslationPresentation.compact.minimumSize.height, ceil(measuredHeight)),
            min(720, max(0, available)))
    }
}

enum TranslationDismissalPolicy {
    static func shouldDismiss(presentation: TranslationPresentation, isVisible: Bool,
                              clickIsInside: Bool, menuIsTracking: Bool,
                              hasModal: Bool, isAssistiveKeyboard: Bool) -> Bool {
        presentation == .compact && isVisible && !clickIsInside &&
            !menuIsTracking && !hasModal && !isAssistiveKeyboard
    }
}

/// Only timings and app identifiers are retained; never key contents.
struct TranslationDoubleCopyDetector {
    static let interval: TimeInterval = 0.7
    private var firstCopy: (time: TimeInterval, pid: Int32)?
    private var lastTrigger: TimeInterval = -.infinity

    mutating func observe(isCopy: Bool, isRepeat: Bool, time: TimeInterval, pid: Int32) -> Bool {
        guard !isRepeat else { return false }
        guard isCopy else { firstCopy = nil; return false }
        guard time - lastTrigger > Self.interval else { firstCopy = nil; return false }
        if let first = firstCopy, first.pid == pid,
           time >= first.time, time - first.time <= Self.interval {
            firstCopy = nil
            lastTrigger = time
            return true
        }
        firstCopy = (time, pid)
        return false
    }
}

enum TranslationInputError: Error { case empty, tooLong, sensitive }

/// Bound work without splitting or rewriting the selected text.
enum TranslationTextPlan {
    static let maximumCharacters = 40_000
    static let protectedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    static func validate(_ text: String, types: Set<String> = []) throws -> String {
        guard protectedTypes.isDisjoint(with: types) else { throw TranslationInputError.sensitive }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw TranslationInputError.empty
        }
        guard text.count <= maximumCharacters else { throw TranslationInputError.tooLong }
        return text
    }

    static func isFreshCopy(baseline: Int?, current: Int) -> Bool {
        guard let baseline else { return false }
        return baseline != current
    }

    static func translate(_ text: String,
                          using engine: (String) async throws -> String) async throws -> String {
        let input = try validate(text)
        try Task.checkCancellation()
        let output = try await engine(input)
        try Task.checkCancellation()
        return output
    }
}

struct TranslationRequest: Equatable {
    let id = UUID()
    let text: String
    let source: String?
    let target: String
    let engine: TranslationEngine

    init(text: String, source: String?, target: String, engine: TranslationEngine = .apple) {
        self.text = text
        self.source = source
        self.target = target
        self.engine = engine
    }
}

/// Invalidates reads/results after another invocation, edits, cancellation or close.
struct TranslationGeneration {
    private(set) var current = UUID()
    @discardableResult mutating func advance() -> UUID { current = UUID(); return current }
    func accepts(_ token: UUID) -> Bool { token == current }
}
